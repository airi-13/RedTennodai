-- 教材を複数科目に紐付け、「全学年」を学年横断として扱う。
-- 今回提示された教材マスタで既存データを置き換える。

ALTER TABLE textbooks
  ADD COLUMN IF NOT EXISTS subjects TEXT[];

-- 既存の subject を新しい複数科目配列へ移行
UPDATE textbooks
SET subjects = ARRAY[subject]
WHERE subjects IS NULL;

ALTER TABLE textbooks
  ALTER COLUMN subjects SET NOT NULL;

ALTER TABLE textbooks
  DROP CONSTRAINT IF EXISTS textbooks_subject_check;
ALTER TABLE textbooks
  ADD CONSTRAINT textbooks_subject_check
  CHECK (
    subject IN ('英語', '国語', '数学', '理科', '社会')
    AND subjects <@ ARRAY['英語', '国語', '数学', '理科', '社会']::TEXT[]
    AND cardinality(subjects) > 0
  );

ALTER TABLE textbooks
  DROP CONSTRAINT IF EXISTS textbooks_level_grade_check;
ALTER TABLE textbooks
  ADD CONSTRAINT textbooks_level_grade_check
  CHECK (
    grade_label = '全学年'
    OR (level = '小学生' AND grade_label IN ('1年','2年','3年','4年','5年','6年','新中1'))
    OR (level = '中学生' AND grade_label IN ('1年','2年','3年','新高1'))
    OR (level = '高校生' AND grade_label IN ('1年','2年','3年'))
  );

DELETE FROM textbooks;

